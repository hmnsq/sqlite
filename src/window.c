    sqlite3_تعبير_Delete(db, p->pFilter);
    sqlite3_تعبير_List_Delete(db, p->pPartition);
    sqlite3_تعبير_List_Delete(db, p->pOrderBy);
    sqlite3_تعبير_Delete(db, p->pEnd);
    sqlite3_تعبير_Delete(db, p->pStart);
