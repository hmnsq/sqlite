  پنجره_Rewrite sRewrite;

  أكد( pWin!=0 );
  memset(&sWalker, 0, حجم(Walker));
  memset(&sRewrite, 0, حجم(پنجره_Rewrite));

  sRewrite.pSub = *ppSub;
  sRewrite.pWin = pWin;
