  Parse *pParse = p->pParse;
  کھڑکی *pMWin = p->pMWin;
  Vdbe *v = p->pVdbe;

  صحیح regCRowid = 0;              /* Current rowid value */
  صحیح regCPeer = 0;               /* Current peer values */
  صحیح regRowid = 0;               /* AggStep rowid value */
  صحیح regPeer = 0;                /* AggStep peer values */

  صحیح nPeer;
  صحیح lbl_اگلا;
  صحیح lblBrk;
  صحیح addr_اگلا;
