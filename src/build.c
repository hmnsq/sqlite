  sqlite3_Vdbe_جوڑو_Op2(v, OP_Sorter_اگلا, iSorter, addr2); VdbeCoverage(v);
  sqlite3_Vdbe_Jump_یہاں(v, addr1);

  sqlite3_Vdbe_جوڑو_Op1(v, OP_Close, iTab);
  sqlite3_Vdbe_جوڑو_Op1(v, OP_Close, iIdx);
  sqlite3_Vdbe_جوڑو_Op1(v, OP_Close, iSorter);
