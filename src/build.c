  sqlite3_Generate_اشاریہ_کلید(pParse,p_اشاریہ,iTab,reg_ریکارڈ,0,&iPartIdxLabel,0,0);
  sqlite3_Vdbe_جوڑو_Op2(v, OP_Sorter_داخل_کرو, iSorter, reg_ریکارڈ);
