  VdbeOp *aOp;                  /* Array of opcodes for sub-program */
  ಪೂರ್ಣಾಂಕ nOp;                      /* Elements in aOp[] */
  ಪೂರ್ಣಾಂಕ nMem;                     /* Number of memory cells required */
  ಪೂರ್ಣಾಂಕ nCsr;                     /* Number of cursors required */
